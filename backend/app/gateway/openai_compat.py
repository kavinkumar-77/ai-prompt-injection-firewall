"""OpenAI-compatible schema definitions for Project AEGIS Gateway."""

from __future__ import annotations

import time
import uuid
from typing import Any, Literal

from pydantic import BaseModel, Field

from app.core.models import TrustSource


class ChatMessage(BaseModel):
    """Single turn in a chat conversation."""

    role: Literal["system", "user", "assistant", "tool"] = Field(
        ..., description="Role of the message author"
    )
    content: str = Field(default="", description="The contents of the message")
    name: str | None = Field(default=None, description="Optional name of the participant")
    tool_calls: list[dict[str, Any]] | None = Field(
        default=None, description="Tool calls generated by the model"
    )
    tool_call_id: str | None = Field(
        default=None, description="Tool call that this message is responding to"
    )
    aegis_source: TrustSource | None = Field(
        default=None,
        description="Explicit AEGIS trust level for this message",
    )


class ChatCompletionRequest(BaseModel):
    """Standard OpenAI-compatible request payload for chat completions."""

    model: str = Field(default="llama3", description="Target model name or checkpoint")
    messages: list[ChatMessage] = Field(
        ..., min_length=1, description="List of messages in context"
    )
    temperature: float = Field(default=0.7, ge=0.0, le=2.0)
    max_tokens: int | None = Field(default=None, ge=1)
    stream: bool = Field(default=False, description="Whether to stream response tokens via SSE")
    tools: list[dict[str, Any]] | None = Field(default=None, description="Available agent tools")
    tool_choice: Any | None = Field(default=None, description="Tool choice mode")
    aegis_include_details: bool = Field(
        default=False,
        description="Whether to include full layer findings in response body",
    )


class ChatCompletionChoice(BaseModel):
    index: int = 0
    message: ChatMessage
    finish_reason: str = "stop"


class ChatCompletionUsage(BaseModel):
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0


class ChatCompletionResponse(BaseModel):
    """Standard OpenAI-compatible non-streaming response body."""

    id: str = Field(default_factory=lambda: f"chatcmpl-{uuid.uuid4().hex[:12]}")
    object: str = "chat.completion"
    created: int = Field(default_factory=lambda: int(time.time()))
    model: str
    choices: list[ChatCompletionChoice]
    usage: ChatCompletionUsage = Field(default_factory=ChatCompletionUsage)
    aegis: dict[str, Any] | None = None


class StreamDelta(BaseModel):
    role: str | None = None
    content: str | None = None
    tool_calls: list[dict[str, Any]] | None = None


class ChatCompletionChunkChoice(BaseModel):
    index: int = 0
    delta: StreamDelta
    finish_reason: str | None = None


class ChatCompletionChunk(BaseModel):
    """Single server-sent event chunk in a streaming chat completion."""

    id: str = Field(default_factory=lambda: f"chatcmpl-{uuid.uuid4().hex[:12]}")
    object: str = "chat.completion.chunk"
    created: int = Field(default_factory=lambda: int(time.time()))
    model: str
    choices: list[ChatCompletionChunkChoice]


class OpenAIErrorDetail(BaseModel):
    message: str
    type: str = "aegis_policy_violation"
    param: str | None = "messages"
    code: str | None = "prompt_injection_blocked"


class OpenAIErrorResponse(BaseModel):
    """OpenAI standard error response body format."""

    error: OpenAIErrorDetail


class ModelItem(BaseModel):
    id: str
    object: str = "model"
    created: int = Field(default_factory=lambda: int(time.time()))
    owned_by: str = "aegis"


class ModelListResponse(BaseModel):
    object: str = "list"
    data: list[ModelItem]
